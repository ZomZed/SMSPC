"""Build the PC port (milestone 2: objects + link census).

    python port/tools/build_port.py            # configure + build + link
    python port/tools/build_port.py --stubs    # also regenerate port/src/stubs_auto.cpp
                                               # from the current undefined symbols

Compiles every game + JSystem unit that passes the census, plus port/src/*.cpp,
into port/build/obj, then links port/build/sms_port.exe with lld-link.
Undefined symbols are written to port/build/undefined.txt. With --stubs, each
one becomes a logging stub in port/src/stubs_auto.cpp so the link succeeds and
the remaining work is an explicit list.
"""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import census  # noqa: E402
import sjis_mirror  # noqa: E402

ROOT = census.ROOT
OUT = ROOT / "port" / "build"
SJIS = OUT / "sjis"  # Shift-JIS literal copies of sources/headers
MIRRORED = set()
LLVM = census.VS_LLVM
CLANG = str(LLVM / "clang.exe")
LLD = str(LLVM / "lld-link.exe")
NINJA = [sys.executable, "-m", "ninja"]


def flags(lang_c):
    f = ["--target=x86_64-pc-windows-msvc", "-c", "-O1", "-g", "-gcodeview", "-fno-exceptions",
         "-fno-rtti", "-fsigned-char", "-w", "-Wno-everything", "-fms-runtime-lib=dll",
         "-include", "port/include/port_compat.h"]
    f += ["-x", "c", "-std=gnu99"] if lang_c else ["-x", "c++", "-std=gnu++17"]
    for i in census.INCLUDES:  # Shift-JIS copies of headers first (sjis_mirror.py)
        f += ["-I", (SJIS / i).relative_to(ROOT).as_posix()]
    for i in census.INCLUDES:
        f += ["-I", i]
    for d in census.DEFINES:
        f += ["-D", d]
    return f


def q(s):
    return s.replace(" ", "$ ").replace(":", "$:")


def write_ninja(us):
    lines = ["ninja_required_version = 1.3", f"builddir = {OUT.as_posix()}", "",
             f"rule cc\n  command = \"{CLANG}\" $flags $in -o $out -MD -MF $out.d\n"
             f"  depfile = $out.d\n  deps = gcc\n  description = CC $in", "",
             f"rule link\n  command = \"{LLD}\" /nologo /subsystem:console /debug /demangle:no /stack:0x800000 /errorlimit:0 "
             f"/out:$out @$out.rsp /defaultlib:msvcrt /defaultlib:ucrt /defaultlib:vcruntime "
             f"/defaultlib:legacy_stdio_definitions /defaultlib:winmm /defaultlib:user32 "
             f"/defaultlib:gdi32 /ignore:4217\n  rspfile = $out.rsp\n  rspfile_content = $in\n"
             f"  description = LINK $out", ""]
    objs = []
    for u in us:
        src = u["src"]
        obj = (OUT / "obj" / (src + ".obj")).as_posix()
        fl = flags(src.endswith(".c") and not src.startswith("libs/JSystem/"))
        if u.get("pch"):
            pch = "include/SMS.pch"
            fl += ["-include", (SJIS / pch).relative_to(ROOT).as_posix() if pch in MIRRORED else pch]
        inp = (SJIS / src).relative_to(ROOT).as_posix() if src in MIRRORED else src
        lines.append(f"build {q(obj)}: cc {q(inp)}\n  flags = {' '.join(fl)}")
        objs.append(obj)
    for p in sorted((ROOT / "port" / "src").glob("*.c*")):
        if p.name in ("port_main.cpp", "port_aurora_sdk.cpp"):  # Aurora build only
            continue
        rel = p.relative_to(ROOT).as_posix()
        obj = (OUT / "obj" / (rel + ".obj")).as_posix()
        fl = flags(p.suffix == ".c")
        lines.append(f"build {q(obj)}: cc {q(rel)}\n  flags = {' '.join(fl)}")
        objs.append(obj)
    exe = (OUT / "sms_port.exe").as_posix()
    lines.append(f"build {q(exe)}: link {' '.join(q(o) for o in objs)}")
    lines.append(f"default {q(exe)}")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "build.ninja").write_text("\n".join(lines) + "\n", encoding="utf-8")


def gen_stubs(undef):
    """Write a logging stub for every undefined symbol (functions get a body that logs
    once and returns 0; this is only meant to make the link succeed)."""
    out = ["// AUTO-GENERATED by port/tools/build_port.py --stubs. Do not edit by hand:",
           "// implement the real function elsewhere in port/src and regenerate.",
           '#include "port_stubs.h"', ""]
    for i, s in enumerate(sorted(undef)):
        esc = s.replace("\\", "\\\\").replace('"', '\\"')
        out.append(f'extern "C" __attribute__((used)) const char kS{i}[] = "{esc}";')
        out.append('asm(".globl \\"' + esc + '\\"\\n\\"' + esc + '\\":\\n'
                   f'  subq $40, %rsp\\n  leaq kS{i}(%rip), %rcx\\n  callq port_missing_stub\\n'
                   '  addq $40, %rsp\\n  retq\\n");')
    (ROOT / "port" / "src" / "stubs_auto.cpp").write_text("\n".join(out) + "\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stubs", action="store_true")
    ap.add_argument("-j", type=int, default=0)
    a = ap.parse_args()
    if a.stubs:  # start from an empty stub file so stale stubs can't collide
        (ROOT / "port" / "src" / "stubs_auto.cpp").write_text("// regenerated below\n", encoding="utf-8")
    res = json.loads((ROOT / "port" / "census.json").read_text())
    us = [r for r in res if r["status"] == "ok"]
    MIRRORED.update(sjis_mirror.mirror(ROOT, ["src", "include", "libs"], SJIS))
    write_ninja(us)
    cmd = NINJA + ["-f", str(OUT / "build.ninja")] + (["-j", str(a.j)] if a.j else []) + ["-k", "0"]
    p = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, errors="replace")
    log = p.stdout + p.stderr
    (OUT / "build.log").write_text(log, encoding="utf-8")
    failed_cc = re.findall(r"FAILED: (\S+\.obj)", log)
    undef = sorted(set(re.findall(r"undefined symbol: (.+)", log)))
    (OUT / "undefined.txt").write_text("\n".join(undef), encoding="utf-8")
    print(f"compile failures: {len(failed_cc)}  undefined symbols: {len(undef)}  "
          f"exe: {'yes' if (OUT / 'sms_port.exe').exists() and p.returncode == 0 else 'no'}")
    if a.stubs and undef:
        gen_stubs(undef)
        print("regenerated port/src/stubs_auto.cpp; run again to link")


if __name__ == "__main__":
    main()
