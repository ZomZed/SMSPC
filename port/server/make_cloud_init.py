"""Writes port/server/cloud-init.yaml: the lobby server, its systemd unit and the VM firewall
rule in one file, pasted into the cloud console's "user data" / "cloud-init script" box when the
VM is created (Oracle: Show advanced options > Management > Paste cloud-init script; Google,
Ubuntu image: Advanced > Management > Metadata, key "user-data"). No SSH or file copying
needed. Re-run after editing sms_lobby_server.py.
"""
import base64
import gzip
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
PORT = 7700
# --no-relay: Google Cloud (1 GB/month free egress) -> cloud-init-gcp.yaml, rendezvous only
NO_RELAY = "--no-relay" in sys.argv
OUT_NAME = "cloud-init-gcp.yaml" if NO_RELAY else "cloud-init.yaml"


def b64(path):
    return base64.b64encode(path.read_bytes()).decode()


def gzb64(path):
    # gzip + base64: keeps the whole script under Oracle's 32000-byte metadata limit
    return base64.b64encode(gzip.compress(path.read_bytes(), 9, mtime=0)).decode()


unit = (HERE / "sms-lobby.service").read_text()
if NO_RELAY:
    unit = unit.replace("--port 7700", "--port 7700 --no-relay")
RUNCMD_LIST = [
    f'id smslobby || useradd --system --no-create-home --shell /usr/sbin/nologin smslobby || useradd -r -M -s /sbin/nologin smslobby',
    f'sed -i "s|^ExecStart=/usr/bin/python3|ExecStart=$(command -v python3)|" /etc/systemd/system/sms-lobby.service',
    f'if command -v ufw >/dev/null && ufw status | grep -q "Status: active"; then ufw allow {PORT}/udp; fi',
    f'if command -v firewall-cmd >/dev/null && firewall-cmd --state; then firewall-cmd --permanent --add-port={PORT}/udp && firewall-cmd --reload; fi',
    f'if command -v iptables >/dev/null; then iptables -C INPUT -p udp --dport {PORT} -j ACCEPT || iptables -I INPUT 1 -p udp --dport {PORT} -j ACCEPT; fi',
    f'if command -v netfilter-persistent >/dev/null; then netfilter-persistent save; elif [ -d /etc/iptables ]; then iptables-save > /etc/iptables/rules.v4; fi',
    f'systemctl daemon-reload',
    f'systemctl enable --now sms-lobby',
]
# single-quoted for YAML: a ": " inside a plain scalar turns the line into a mapping
RUNCMD = "\n".join("  - '" + c.replace("'", "''") + "'" for c in RUNCMD_LIST)
out = f"""#cloud-config
# Super Mario Sunshine PC port lobby server (generated by make_cloud_init.py; do not edit).
# Installs /opt/sms-lobby/sms_lobby_server.py as the systemd service "sms-lobby" on UDP {PORT}
# and opens that port in the VM's own firewall. The cloud firewall (Oracle security list /
# Google VPC rule) still needs an ingress rule for UDP {PORT}: see DEPLOY.md.
package_update: false
packages: [python3]
write_files:
  - path: /opt/sms-lobby/sms_lobby_server.py
    permissions: "0755"
    encoding: gz+b64
    content: {gzb64(HERE / "sms_lobby_server.py")}
  - path: /etc/systemd/system/sms-lobby.service
    permissions: "0644"
    encoding: b64
    content: {base64.b64encode(unit.encode()).decode()}
runcmd:
{RUNCMD}
"""
(HERE / OUT_NAME).write_text(out, newline="\n")
print(f"wrote {HERE / OUT_NAME} ({len(out)} bytes)")
